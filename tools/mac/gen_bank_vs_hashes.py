#!/usr/bin/env python3
"""Writes src/gpu/shaders/bank_vs_hashes.inc: the run-time hashes (XXH3-64 of virtual ++ physical part) of the
vertex shader containers of Fable II's shader bank, sorted, one 0x...ull per line.

    gen_bank_vs_hashes.py --bank <game>/data/Shaders/ShadersRelease.sbk --out src/gpu/shaders/bank_vs_hashes.inc

The renderer (vs_identity.cpp) only adopts a container as a vertex shader's pristine original when its hash is in
this table: a rewritten form, or anything else the game leaves in a shader object, never is. Hashes only, no game
data. The bank reader and XXH3 are extract_shaders.py's.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import extract_shaders as ex


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--bank", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    items = ex.extract_all(a.bank)
    hashes = sorted({h for h, kind, _ in items if kind & 1})  # bit 0 = vertex (a few bank containers already carry 0x40)
    with open(a.out, "w") as f:
        f.write("// Generated by tools/mac/gen_bank_vs_hashes.py from the shader bank: the hashes of its %d vertex shader\n"
                "// containers, sorted (vs_identity.cpp).\n" % len(hashes))
        for h in hashes:
            f.write("0x%016xull,\n" % h)
    print("%d vertex shader hashes" % len(hashes))


if __name__ == "__main__":
    main()
